#define GUA_COUNT 64

/**
 * @brief 根据阴阳数组查找卦在数据表中的索引
 * @param yin_yang 阴阳数组 [6]
 * @return 卦索引 (0-63)，找不到返回 -1
 */
static inline int gua_find_index(const int8_t yin_yang[6])
{
    for (int i = 0; i < GUA_COUNT; i++) {
        int match = 1;
        for (int j = 0; j < 6; j++) {
            if (gua_data[i].yin_yang[j] != yin_yang[j]) {
                match = 0;
                break;
            }
        }
        if (match) return i;
    }
    return -1;
}

